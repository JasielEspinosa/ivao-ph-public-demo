// Stamps every build with a version so a deployment can be detected by the running app.
// Writes public/version.json (served fresh, never cached) and src/environments/build-info.ts (baked into the bundle).
// Version source: APP_VERSION env/build-arg (Docker has no .git), else git short SHA, else timestamp.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const builtAt = new Date().toISOString();

function resolveVersion() {
  if (process.env.APP_VERSION && process.env.APP_VERSION.trim()) {
    return process.env.APP_VERSION.trim();
  }
  try {
    return execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    return '';
  }
}

// Always unique per build, even when the same commit is rebuilt.
const base = resolveVersion();
const version = base ? `${base}-${builtAt.replace(/\D/g, '').slice(0, 14)}` : builtAt.replace(/\D/g, '').slice(0, 14);

writeFileSync(resolve(root, 'public/version.json'), JSON.stringify({ version, builtAt }) + '\n');
writeFileSync(
  resolve(root, 'src/environments/build-info.ts'),
  `// Generated by scripts/generate-version.mjs. Do not edit or commit.\nexport const BUILD_VERSION = '${version}';\n`,
);
console.log(`Build version: ${version}`);
